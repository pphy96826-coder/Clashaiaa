class ActionExecutor:
    # Keep input strictly serial. Card selection, placement and hand rotation
    # share one UI state; overlapping actions can make taps interfere.
    MAX_IN_FLIGHT_ACTIONS = 1

    # Replace the global post-card stall only when a defensive play can be
    # tied to one concrete live enemy.  A short reservation suppresses another
    # card aimed at that same enemy while allowing immediate reactions to a
    # different threat.
    THREAT_RESERVATION_PROVISIONAL_SECONDS = 0.55
    THREAT_RESERVATION_CONFIRMED_SECONDS = 0.85
    THREAT_RESERVATION_UNCERTAIN_SECONDS = 0.70
    THREAT_RESERVATION_RADIUS_WORLD = 6000.0
    # A single enemy play can create several tightly packed bodies (Goblin
    # Barrel/Gang-style threats). Reserving only the nearest entity lets the
    # next policy frame bind to a sibling and spend another defender on the
    # same already-answered play. Group only nearby bodies with the same
    # runtime card identity; unrelated push units remain independently
    # defendable.
    THREAT_COHORT_RADIUS_WORLD = 2800.0
    # Re-identification fallback for probes that replace native entity ids.
    # This is deliberately tighter than the general threat radius so a
    # separate same-card push in another lane remains independently defendable.
    THREAT_REBIND_RADIUS_WORLD = 4200.0
    # Keep a short reaction-pending window after Android input completion.
    # During this window the next policy frame must not answer the same cohort
    # again just because the spell/troop effect has not rendered yet. After a
    # genuinely newer probe frame and this delay, the residual threat is
    # re-evaluated instead of being hard-blocked until every body disappears.
    # Resource budget is the primary repeated-defense gate. Keep only a very
    # short render grace for unsupported/unknown-cost threats.
    THREAT_REACTION_HOLD_SECONDS = 0.12
    THREAT_BUDGET_RADIUS_WORLD = 6500.0
    THREAT_GROUP_JOIN_RADIUS_WORLD = 5200.0
    THREAT_GROUP_DEFENSE_RADIUS_WORLD = 4600.0
    THREAT_GROUP_REBIND_RADIUS_WORLD = 5200.0
    THREAT_LARGE_PUSH_MARGIN_COST = 1.0
    # Residual threat must never be judged while the original card is still
    # awaiting its ACK outcome. Once that outcome arrives, start a new,
    # shorter effect-observation window from the ACK/timeout itself. Spells
    # need a little less time than troops/buildings because their impact is
    # immediate once accepted; deployables need a few extra frames to begin
    # interacting with the threat.
    THREAT_POST_ACK_SPELL_GRACE_SECONDS = 0.30
    THREAT_POST_ACK_DEPLOY_GRACE_SECONDS = 0.45
    THREAT_POST_TIMEOUT_GRACE_SECONDS = 0.35
    THREAT_MOSTLY_HANDLED_GRACE_SECONDS = 0.35
    THREAT_RESIDUAL_RELEASE_RATIO = 0.55
    # Keep the reservation row alive through slow hand ACK telemetry, but note
    # that expires_at is only bookkeeping. Suppression after the reaction hold
    # is decided from residual threat, not from this long TTL.
    THREAT_PROVISIONAL_ACK_GRACE_SECONDS = 0.30

    def __init__(self, actuator, log, dry_run=False, on_ability_ack=None,
                 max_actions=None, card_cost_resolver=None):
        self.actuator, self.log, self.dry_run = actuator, log, dry_run
        self.card_cost_resolver = card_cost_resolver
        self.on_ability_ack = on_ability_ack
        if max_actions is not None and (type(max_actions) is not int or max_actions <= 0):
            raise ValueError('max_actions must be a positive integer or None')
        self.max_actions = max_actions
        self.attempted_actions = 0
        self.confirmed_actions = 0
        self.pending = []
        self.ack_watch = []
        self.pool = ThreadPoolExecutor(max_workers=1, thread_name_prefix='android-input')
        self.future = None
        self.active = None
        self.cooldowns = {}
        # A non-hand ACK (spawn/elixir) proves the input probably landed but
        # does not prove that the native hand snapshot has rotated yet. Keep
        # that exact slot/card locally blocked until the authoritative hand
        # transition arrives, without freezing other slots.
        self.slot_consume_guards = {}
        # When the native cycle has advanced but one hand slot is still stale,
        # keep a conservative effective-card overlay for that slot. The raw
        # hand remains untouched for ACK evidence; policy/validation receive
        # only cycle-proven replacements.
        self.slot_hand_overrides = {}
        self.unconfirmed_spend = []
        self.predictions = []
        self.threat_reservations = []
        self.fault = None
        self.spawn_watch = []
        self.ability_locks = set()
        self._next_command_seq = 1
        self._fresh_state_required = False
        self._decision_blocked_until = 0.0
        self._recent_misses = {}
        self._confirmed_for_simulation = []
        self._latency_samples_ms = []
        self._ack_latency_samples_ms = []
        self.end_to_end_latency_ms = float(config.PREDICTION_LATENCY_COMPENSATION_MS)
        self._post_action_settle_tick = -1
        self._post_action_preview = None

    def _in_flight_count(self):
        return len(self.pending) + len(self.spawn_watch)

    def reset(self):
        # Do not carry queued actions, reservations or locks across matches.
        # An already submitted Android command cannot be unsent.
        self.pending.clear()
        self.ack_watch.clear()
        self.spawn_watch.clear()
        self.cooldowns.clear()
        self.slot_consume_guards.clear()
        self.slot_hand_overrides.clear()
        self.unconfirmed_spend.clear()
        self.predictions.clear()
        self.threat_reservations.clear()
        self.ability_locks.clear()
        self.fault = None
        self.attempted_actions = 0
        self.confirmed_actions = 0
        self._fresh_state_required = False
        self._decision_blocked_until = 0.0
        self._recent_misses.clear()
        self._confirmed_for_simulation.clear()
        self._ack_latency_samples_ms.clear()
        self._post_action_settle_tick = -1
        self._post_action_preview = None

    def consume_fresh_state_required(self):
        """Return whether the caller must fetch a new probe frame first."""
        required = self._fresh_state_required
        self._fresh_state_required = False
        return required

    def consume_confirmed_for_simulation(self):
        """Return card accepts not yet visible in rich combat events."""
        actions = tuple(self._confirmed_for_simulation)
        self._confirmed_for_simulation.clear()
        return actions

    @property
    def action_budget_exhausted(self):
        return (self.max_actions is not None
                and self.attempted_actions >= self.max_actions)

    @property
    def action_budget_settled(self):
        """Budget is spent and every submitted touch has a final ACK outcome."""
        return (self.action_budget_exhausted
                and self.future is None
                and not self.pending
                and not self.ack_watch)

    def decision_blocked(self, state=None):
        """Whether a new policy turn must wait for an authoritative frame."""
        if time.perf_counter() < self._decision_blocked_until:
            return True
        return state is not None and self._post_action_settle_tick >= 0 and state.tick < self._post_action_settle_tick


    def prelock_reserved_threat_ids(self, state):
        """Return active threat IDs whose submitted response still suppresses."""
        if state is None:
            return frozenset()

        now = time.perf_counter()
        self._prune_threat_reservations(state, now)

        ids = set()

        for reservation in tuple(self.threat_reservations):
            suppress, _, _ = self._reservation_still_suppresses(
                reservation, state, now)

            if suppress:
                ids.update(int(v) for v in reservation.threat_ids)

        return frozenset(ids)

    def prelock_reservation_conflict(self, context, state):
        """Whether this urgent enemy already has an active response."""
        if not context or state is None:
            return False

        enemy_id = int(context.get('enemy_id') or 0)

        if enemy_id <= 0:
            return False

        if enemy_id not in self.prelock_reserved_threat_ids(state):
            return False

        enemy = next((
            entity for entity in state.entities
            if int(entity.get('id', -1)) == enemy_id
        ), None)

        if enemy is not None and self.card_cost_resolver is not None:
            x, y = enemy.get('x'), enemy.get('y')
            if isinstance(x, (int, float)) and isinstance(y, (int, float)):
                target = (float(x), float(y))
                attack_budget = self._local_live_card_cost(
                    state,
                    1 - int(state.local_owner),
                    target,
                    int(state.local_owner),
                )
                board_defense = self._local_live_card_cost(
                    state,
                    int(state.local_owner),
                    target,
                    int(state.local_owner),
                )
                reserved_defense = self._local_reserved_defense_cost(
                    int(state.local_owner),
                    target,
                )
                committed = max(board_defense, reserved_defense)
                margin = (
                    self.THREAT_LARGE_PUSH_MARGIN_COST
                    if attack_budget >= 5.0 else 0.0
                )
                if (
                    attack_budget > 0.0
                    and committed < attack_budget + margin
                ):
                    return False

        return True

    def interrupt_post_action_recheck(self, context, state):
        """Allow a genuinely new urgent threat to bypass the old preview."""
        if not context:
            return False

        if self.prelock_reservation_conflict(context, state):
            return False

        if self._post_action_settle_tick >= 0:
            self.log(
                'prelock_post_action_interrupted',
                enemy_id=context.get('enemy_id'),
                enemy_card_id=context.get('enemy_card_id'),
                prelock_state=context.get('state'),
                reason=context.get('reason'),
                latest_safe_response_ms=context.get(
                    'latest_safe_response_ms'),
                previous_settle_tick=self._post_action_settle_tick,
            )

            self._post_action_settle_tick = -1
            self._post_action_preview = None

        return True

    def _card_ack_timeout_seconds(self):
        """Return a bounded ACK budget without stalling unrelated slots.

        Card ACK telemetry can lag Android input completion by more than a
        second on busy emulator frames. Keep a conservative live-safe floor,
        expand it modestly when recent input/ACK latency is slow, and cap the
        adaptive window so genuine misses still settle promptly. Active ACK
        watches keep their spend reserved independently of the age TTL, and
        only the submitted slot remains locked while this budget runs.
        """
        timeout = float(config.CARD_ACK_TIMEOUT_BASE_SECONDS)
        input_based = (
            float(config.ACK_TIMEOUT_SECONDS)
            + float(config.CARD_ACK_TIMEOUT_INPUT_MULTIPLIER)
            * max(0.0, float(self.end_to_end_latency_ms)) / 1000.0
        )
        timeout = max(timeout, input_based)
        # The first few authoritative card ACKs are the only live phase where
        # the guest hand/probe path repeatedly exceeded the normal floor.
        # Borrow the already-bounded max window until enough strong hand/cycle
        # samples exist; after that, use the recent strong-ACK p90 + margin.
        if len(self._ack_latency_samples_ms) < int(config.CARD_ACK_BOOTSTRAP_SAMPLES):
            return float(config.CARD_ACK_TIMEOUT_MAX_SECONDS)
        if self._ack_latency_samples_ms:
            ordered = sorted(self._ack_latency_samples_ms[-12:])
            # Use the recent strong-ACK p90.  Weak elixir/entity fallbacks are
            # intentionally excluded from this sample set because they can be
            # hundreds of milliseconds faster than authoritative hand/cycle
            # consumption telemetry and would otherwise pull the timeout down.
            index = max(0, min(len(ordered) - 1, math.ceil(len(ordered) * 0.9) - 1))
            observed = (
                ordered[index] / 1000.0
                + float(config.CARD_ACK_TIMEOUT_MARGIN_SECONDS)
            )
            timeout = max(timeout, observed)
        return max(
            float(config.CARD_ACK_TIMEOUT_BASE_SECONDS),
            min(float(config.CARD_ACK_TIMEOUT_MAX_SECONDS), timeout),
        )

    def _record_card_ack_latency(self, latency_ms, evidence=None):
        # Only authoritative consumption evidence should tune the slow-path
        # timeout.  Elixir-drop / entity-spawn ACKs remain valid immediate ACKs
        # but are often much faster than native hand telemetry.
        if evidence not in ('hand_rotation', 'native_cycle_transition'):
            return
        if not isinstance(latency_ms, (int, float)) or not math.isfinite(latency_ms):
            return
        if latency_ms < 0:
            return
        self._ack_latency_samples_ms.append(float(latency_ms))
        self._ack_latency_samples_ms[:] = self._ack_latency_samples_ms[-12:]

    @staticmethod
    def _candidate_key(decoded):
        action = next((item for item in decoded.actions if item.kind.value != 'wait'), None)
        if action is None:
            return None
        return (action.kind.value, int(action.card_id or 0),
                int(action.hand_slot if action.hand_slot is not None else -1),
                int(action.source_entity if action.source_entity is not None else -1),
                tuple(action.target_grid) if action.target_grid is not None else None)

    @staticmethod
    def _candidate_score(decoded):
        action = next((item for item in decoded.actions if item.kind.value != 'wait'), None)
        if action is None:
            return 0.0
        value = action.metadata.get('policy_sequence_probability', 0.0)
        return float(value) if isinstance(value, (int, float)) and math.isfinite(value) else 0.0

    def _arm_post_action_recheck(self, state, pending, *, reason):
        """Require a settled no-write preview before the next card input."""
        settle_tick = int(state.tick) + config.POST_ACTION_SETTLE_TICKS
        self._post_action_settle_tick = max(self._post_action_settle_tick, settle_tick)
        self._post_action_preview = None
        self.log('post_action_settle_armed', command_seq=pending.command_seq,
                 card=pending.action.card_id, reason=reason,
                 observed_tick=state.tick, settle_tick=self._post_action_settle_tick,
                 settle_ticks=config.POST_ACTION_SETTLE_TICKS)

    def post_action_recheck(self, decoded, state):
        """Return true only when a post-card candidate remains stable.

        The first settled inference is deliberately preview-only.  The next
        policy frame may submit only the same first action and only if its
        selected-sequence score has retained enough of that preview score.
        """
        if self._post_action_settle_tick < 0:
            return True
        if state.tick < self._post_action_settle_tick:
            return False
        key = self._candidate_key(decoded)
        score = self._candidate_score(decoded)
        if self._post_action_preview is None:
            self._post_action_preview = {'key': key, 'score': score, 'tick': int(state.tick)}
            self.log('post_action_preview', tick=state.tick, candidate=key,
                     sequence_probability=score, write_suppressed=True)
            # A WAIT preview has already answered the question: no second
            # response is currently warranted.  Return to normal cadence.
            if key is None:
                self._post_action_settle_tick = -1
                self._post_action_preview = None
            return False
        preview = self._post_action_preview
        self._post_action_settle_tick = -1
        self._post_action_preview = None
        minimum = preview['score'] * config.POST_ACTION_RECHECK_MIN_SCORE_RATIO
        accepted = key is not None and key == preview['key'] and score >= minimum
        self.log('post_action_recheck', tick=state.tick, preview_candidate=preview['key'],
                 candidate=key, preview_probability=preview['score'],
                 sequence_probability=score, minimum_probability=minimum,
                 accepted=accepted)
        return accepted

    @staticmethod
    def _action_key(action):
        return (int(action.card_id or 0), int(action.hand_slot if action.hand_slot is not None else -1),
                tuple(action.target_grid) if action.target_grid is not None else None)

    @staticmethod
    def _on_own_half(owner, y):
        return float(y) <= 16000.0 if owner == 0 else float(y) >= 16000.0

    def _card_cost(self, card_id):
        if self.card_cost_resolver is None:
            return 0.0
        try:
            value = float(self.card_cost_resolver(int(card_id)))
        except (TypeError, ValueError, KeyError):
            return 0.0
        return value if math.isfinite(value) and value > 0.0 else 0.0

    def _entity_source_card_id(self, entity):
        origin = entity.get('deployment_origin')
        if isinstance(origin, dict):
            source = origin.get('source_card_id')
            if isinstance(source, int) and self._card_cost(source) > 0.0:
                return int(source)
        cid = entity.get('card_id')
        if isinstance(cid, int) and self._card_cost(cid) > 0.0:
            return int(cid)
        return None

    @staticmethod
    def _entity_budget_group_key(entity, source_card_id):
        origin = entity.get('deployment_origin')
        if isinstance(origin, dict):
            epoch = origin.get('epoch')
            sequence = origin.get('sequence')
            if isinstance(epoch, int) and isinstance(sequence, int):
                return (
                    'deployment',
                    int(entity.get('owner', -1)),
                    epoch,
                    sequence,
                )
        return (
            'local-card',
            int(entity.get('owner', -1)),
            int(source_card_id),
        )

    @staticmethod
    def _threat_group_lane(x):
        return 'left' if float(x) < 9000.0 else 'right'

    def _threat_group_rows(self, state, defending_owner):
        rows = []
        for entity in state.entities:
            if int(entity.get('owner', -1)) == int(defending_owner):
                continue
            entity_id = entity.get('id')
            card_id = entity.get('card_id')
            hp = entity.get('hp')
            x, y = entity.get('x'), entity.get('y')
            if (
                not isinstance(entity_id, int)
                or entity_id <= 0
                or not isinstance(card_id, int)
                or card_id <= 0
                or not isinstance(hp, (int, float))
                or float(hp) <= 0.0
                or not isinstance(x, (int, float))
                or not isinstance(y, (int, float))
                or not self._on_own_half(defending_owner, y)
            ):
                continue
            source = self._entity_source_card_id(entity)
            if source is None:
                continue
            origin = entity.get('deployment_origin')
            root = None
            if isinstance(origin, dict):
                epoch = origin.get('epoch')
                sequence = origin.get('sequence')
                if isinstance(epoch, int) and isinstance(sequence, int):
                    root = ('deployment', int(entity.get('owner', -1)),
                            epoch, sequence)
            rows.append({
                'entity_id': int(entity_id),
                'card_id': int(card_id),
                'source_card_id': int(source),
                'source_root': root,
                'cost': self._card_cost(source),
                'lane': self._threat_group_lane(x),
                'x': float(x),
                'y': float(y),
            })
        return rows

    def _threat_groups(self, state, defending_owner):
        rows = self._threat_group_rows(state, defending_owner)
        if not rows:
            return ()

        parent = list(range(len(rows)))

        def root(index):
            while parent[index] != index:
                parent[index] = parent[parent[index]]
                index = parent[index]
            return index

        def union(a, b):
            ra, rb = root(a), root(b)
            if ra != rb:
                parent[rb] = ra

        radius_sq = self.THREAT_GROUP_JOIN_RADIUS_WORLD ** 2
        for i, left in enumerate(rows):
            for j in range(i + 1, len(rows)):
                right = rows[j]
                if left['lane'] != right['lane']:
                    continue
                same_root = (
                    left['source_root'] is not None
                    and left['source_root'] == right['source_root']
                )
                near = (
                    (left['x'] - right['x']) ** 2
                    + (left['y'] - right['y']) ** 2
                    <= radius_sq
                )
                if same_root or near:
                    union(i, j)

        components = {}
        for index, row in enumerate(rows):
            components.setdefault(root(index), []).append(row)

        groups = []
        for members in components.values():
            lane = members[0]['lane']
            source_costs = {}
            # Native deployment roots are exact.  Without one, keep tightly
            # packed same-card children as one source play; separated copies
            # of the same card remain distinct.
            unrooted = []
            for row in members:
                if row['source_root'] is not None:
                    source_costs[row['source_root']] = max(
                        source_costs.get(row['source_root'], 0.0),
                        row['cost'],
                    )
                else:
                    unrooted.append(row)

            unrooted_parent = list(range(len(unrooted)))
            def uroot(index):
                while unrooted_parent[index] != index:
                    unrooted_parent[index] = unrooted_parent[
                        unrooted_parent[index]]
                    index = unrooted_parent[index]
                return index
            def uunion(a, b):
                ra, rb = uroot(a), uroot(b)
                if ra != rb:
                    unrooted_parent[rb] = ra

            cohort_sq = self.THREAT_COHORT_RADIUS_WORLD ** 2
            for i, left in enumerate(unrooted):
                for j in range(i + 1, len(unrooted)):
                    right = unrooted[j]
                    if left['source_card_id'] != right['source_card_id']:
                        continue
                    if (
                        (left['x'] - right['x']) ** 2
                        + (left['y'] - right['y']) ** 2
                        <= cohort_sq
                    ):
                        uunion(i, j)

            for index, row in enumerate(unrooted):
                key = (
                    'observed',
                    int(row['source_card_id']),
                    int(uroot(index)),
                )
                source_costs[key] = max(
                    source_costs.get(key, 0.0),
                    row['cost'],
                )

            anchor_x = sum(row['x'] for row in members) / len(members)
            anchor_y = sum(row['y'] for row in members) / len(members)
            card_ids = frozenset(
                int(row['source_card_id']) for row in members)
            source_tokens = sorted(
                ':'.join(str(part) for part in key)
                for key in source_costs
            )
            # Exact roots give a stable id.  Fallback groups include a broad
            # anchor bucket; matching also uses lane/card signature/anchor so
            # a bucket boundary cannot merge unrelated reservations.
            bucket_x = int(anchor_x // 2500.0)
            bucket_y = int(anchor_y // 2500.0)
            group_id = (
                f"{lane}|{bucket_x}:{bucket_y}|"
                + '|'.join(source_tokens)
            )
            groups.append({
                'group_id': group_id,
                'lane': lane,
                'entity_ids': frozenset(
                    int(row['entity_id']) for row in members),
                'card_ids': card_ids,
                'attack_cost': float(sum(source_costs.values())),
                'anchor': (float(anchor_x), float(anchor_y)),
            })
        return tuple(groups)

    def _threat_group_for_action(self, action, state):
        if (
            self.card_cost_resolver is None
            or action.kind.value != 'play_card'
            or action.target_grid is None
        ):
            return None
        target = action_world(action)
        if not self._on_own_half(action.owner, target[1]):
            return None
        groups = self._threat_groups(state, int(action.owner))
        if not groups:
            return None
        radius_sq = self.THREAT_RESERVATION_RADIUS_WORLD ** 2
        ranked = []
        for group in groups:
            ax, ay = group['anchor']
            distance_sq = (
                (ax - float(target[0])) ** 2
                + (ay - float(target[1])) ** 2
            )
            if distance_sq <= radius_sq:
                ranked.append((distance_sq, group))
        return min(ranked, key=lambda row: row[0])[1] if ranked else None

    def _same_threat_group(self, reservation, group):
        if group is None:
            return False
        reserved_group_id = getattr(
            reservation, 'threat_group_id', None)
        if reserved_group_id and reserved_group_id == group['group_id']:
            return True
        reserved_lane = getattr(
            reservation, 'threat_group_lane', None)
        if reserved_lane and reserved_lane != group['lane']:
            return False
        card_ids = frozenset(
            getattr(reservation, 'threat_card_ids', ()))
        if card_ids and not (card_ids & group['card_ids']):
            return False
        anchor = getattr(reservation, 'threat_anchor', None)
        if anchor is None:
            return False
        return (
            (float(anchor[0]) - group['anchor'][0]) ** 2
            + (float(anchor[1]) - group['anchor'][1]) ** 2
            <= self.THREAT_GROUP_REBIND_RADIUS_WORLD ** 2
        )

    def _local_live_card_cost(self, state, unit_owner, target, reference_owner):
        """Full surviving source-card cost in one local defensive cluster."""
        tx, ty = map(float, target)
        radius_sq = self.THREAT_BUDGET_RADIUS_WORLD ** 2
        groups = {}
        for entity in state.entities:
            if int(entity.get('owner', -1)) != int(unit_owner):
                continue
            hp = entity.get('hp')
            x, y = entity.get('x'), entity.get('y')
            if (
                not isinstance(hp, (int, float))
                or float(hp) <= 0.0
                or not isinstance(x, (int, float))
                or not isinstance(y, (int, float))
                or not self._on_own_half(reference_owner, y)
                or (float(x) - tx) ** 2 + (float(y) - ty) ** 2 > radius_sq
            ):
                continue
            source = self._entity_source_card_id(entity)
            if source is None:
                continue
            key = self._entity_budget_group_key(entity, source)
            groups[key] = max(
                groups.get(key, 0.0),
                self._card_cost(source),
            )
        return sum(groups.values())

    def _local_reserved_defense_cost(
            self, owner, target, threat_group=None):
        tx, ty = map(float, target)
        radius_sq = self.THREAT_BUDGET_RADIUS_WORLD ** 2
        seen = set()
        total = 0.0
        for reservation in self.threat_reservations:
            seq = int(getattr(reservation, 'command_seq', -1))
            if seq in seen:
                continue
            anchor = getattr(reservation, 'target', None)
            if (
                int(getattr(reservation, 'owner', -1)) != int(owner)
                or not isinstance(anchor, tuple)
                or len(anchor) != 2
            ):
                continue
            if (
                threat_group is not None
                and not self._same_threat_group(
                    reservation, threat_group)
            ):
                continue
            if (
                (float(anchor[0]) - tx) ** 2
                + (float(anchor[1]) - ty) ** 2
                > radius_sq
            ):
                continue
            seen.add(seq)
            total += max(
                0.0,
                float(getattr(reservation, 'defense_cost', 0.0)),
            )
        return total

    def _group_live_defense_cost(
            self, state, owner, threat_group):
        ax, ay = threat_group['anchor']
        radius_sq = self.THREAT_GROUP_DEFENSE_RADIUS_WORLD ** 2
        groups = {}
        for entity in state.entities:
            if int(entity.get('owner', -1)) != int(owner):
                continue
            hp = entity.get('hp')
            x, y = entity.get('x'), entity.get('y')
            if (
                not isinstance(hp, (int, float))
                or float(hp) <= 0.0
                or not isinstance(x, (int, float))
                or not isinstance(y, (int, float))
                or self._threat_group_lane(x) != threat_group['lane']
                or (float(x) - ax) ** 2 + (float(y) - ay) ** 2
                    > radius_sq
            ):
                continue
            source = self._entity_source_card_id(entity)
            if source is None:
                continue
            key = self._entity_budget_group_key(entity, source)
            groups[key] = max(
                groups.get(key, 0.0),
                self._card_cost(source),
            )
        return sum(groups.values())

    def _defense_budget_context(self, action, state):
        if (
            self.card_cost_resolver is None
            or action.kind.value != 'play_card'
            or action.target_grid is None
        ):
            return None
        target = action_world(action)
        threat_group = self._threat_group_for_action(
            action, state)
        if threat_group is not None:
            attack_budget = float(
                threat_group['attack_cost'])
            board_defense = self._group_live_defense_cost(
                state,
                int(action.owner),
                threat_group,
            )
            reserved_defense = self._local_reserved_defense_cost(
                int(action.owner),
                target,
                threat_group=threat_group,
            )
        else:
            attack_budget = self._local_live_card_cost(
                state,
                1 - int(action.owner),
                target,
                int(action.owner),
            )
            board_defense = self._local_live_card_cost(
                state,
                int(action.owner),
                target,
                int(action.owner),
            )
            reserved_defense = self._local_reserved_defense_cost(
                int(action.owner),
                target,
            )
        if attack_budget <= 0.0:
            return None
        committed = max(board_defense, reserved_defense)
        margin = (
            self.THREAT_LARGE_PUSH_MARGIN_COST
            if attack_budget >= 5.0 else 0.0
        )
        limit = attack_budget + margin
        candidate_cost = float(
            action.metadata.get('policy_effective_cost', 0.0) or 0.0
        )
        return {
            'attack_budget': attack_budget,
            'board_defense': board_defense,
            'reserved_defense': reserved_defense,
            'committed_defense': committed,
            'budget_limit': limit,
            'candidate_cost': candidate_cost,
            'remaining_before_action': max(0.0, limit - committed),
            'threat_group_id': (
                threat_group['group_id']
                if threat_group is not None else None),
            'threat_group_lane': (
                threat_group['lane']
                if threat_group is not None else None),
        }

    @staticmethod
    def _live_entity_ids(state):
        return frozenset(
            int(entity['id']) for entity in state.entities
            if isinstance(entity.get('id'), int) and entity['id'] > 0
            and isinstance(entity.get('hp'), (int, float)) and entity['hp'] > 0
        )

    def _nearby_threat_ids(self, action, state):
        """Bind a defensive play to one local enemy play/cohort, if possible.

        A multi-body threat must not evade the reservation simply because the
        next frame chooses a different sibling as the nearest entity. Start
        from the nearest concrete enemy, then include only tightly packed
        enemies with the same runtime card identity. This keeps Goblin
        Barrel/Gang-style bodies together without turning a mixed push into one
        giant reservation.
        """
        if action.kind.value != 'play_card' or action.target_grid is None:
            return frozenset()
        if self.card_cost_resolver is not None:
            threat_group = self._threat_group_for_action(
                action, state)
            if threat_group is not None:
                return frozenset(threat_group['entity_ids'])
        target_x, target_y = action_world(action)
        if not self._on_own_half(action.owner, target_y):
            return frozenset()
        radius_sq = self.THREAT_RESERVATION_RADIUS_WORLD ** 2
        candidates = []
        for entity in state.entities:
            if entity.get('owner') == action.owner:
                continue
            entity_id = entity.get('id')
            card_id = entity.get('card_id')
            hp = entity.get('hp')
            x, y = entity.get('x'), entity.get('y')
            # Towers use non-positive card ids in this contract; projectiles
            # and effects either have no positive HP or no source card.
            if not isinstance(entity_id, int) or entity_id <= 0:
                continue
            if not isinstance(card_id, int) or card_id <= 0:
                continue
            if not isinstance(hp, (int, float)) or hp <= 0:
                continue
            if not isinstance(x, (int, float)) or not isinstance(y, (int, float)):
                continue
            if not self._on_own_half(action.owner, y):
                continue
            distance_sq = ((float(x) - target_x) ** 2
                           + (float(y) - target_y) ** 2)
            if distance_sq <= radius_sq:
                candidates.append((distance_sq, entity_id, card_id,
                                   float(x), float(y)))
        if not candidates:
            return frozenset()

        _, primary_id, primary_card, primary_x, primary_y = min(
            candidates, key=lambda row: (row[0], row[1]))
        cohort_radius_sq = self.THREAT_COHORT_RADIUS_WORLD ** 2
        cohort = {
            int(entity_id)
            for _, entity_id, card_id, x, y in candidates
            if int(card_id) == int(primary_card)
            and (x - primary_x) ** 2 + (y - primary_y) ** 2
                <= cohort_radius_sq
        }
        cohort.add(int(primary_id))
        return frozenset(cohort)

    def _prune_threat_reservations(self, state, now=None):
        now = time.perf_counter() if now is None else now
        unresolved = {
            int(getattr(row, 'command_seq', -1))
            for row in self.ack_watch
        }
        self.threat_reservations[:] = [
            reservation for reservation in self.threat_reservations
            if now < reservation.expires_at
            or (
                reservation.confidence == 'provisional'
                and reservation.command_seq in unresolved
            )
        ]

    @staticmethod
    def _threat_metrics(state, threat_ids):
        rows = [
            entity for entity in state.entities
            if entity.get('id') in threat_ids
            and isinstance(entity.get('hp'), (int, float))
            and entity.get('hp') > 0
        ]
        return len(rows), sum(float(entity['hp']) for entity in rows)

    @staticmethod
    def _threat_signature(state, threat_ids):
        rows = [
            entity for entity in state.entities
            if entity.get('id') in threat_ids
            and isinstance(entity.get('card_id'), int)
            and entity.get('card_id') > 0
            and isinstance(entity.get('x'), (int, float))
            and isinstance(entity.get('y'), (int, float))
        ]
        if not rows:
            return frozenset(), None
        card_ids = frozenset(int(entity['card_id']) for entity in rows)
        anchor = (
            sum(float(entity['x']) for entity in rows) / len(rows),
            sum(float(entity['y']) for entity in rows) / len(rows),
        )
        return card_ids, anchor

    def _rebound_threat_ids(
            self, action, state, reservation, candidate_threat_ids=None):
        """Find the same live play after native ids were regenerated."""
        card_ids = frozenset(getattr(reservation, 'threat_card_ids', ()))
        anchor = getattr(reservation, 'threat_anchor', None)
        if not card_ids or anchor is None:
            return frozenset()
        radius_sq = self.THREAT_REBIND_RADIUS_WORLD ** 2
        candidates = []
        for entity in state.entities:
            if entity.get('owner') == action.owner:
                continue
            entity_id = entity.get('id')
            card_id = entity.get('card_id')
            x, y = entity.get('x'), entity.get('y')
            hp = entity.get('hp')
            if (candidate_threat_ids is not None
                    and entity_id not in candidate_threat_ids):
                continue
            if (not isinstance(entity_id, int) or entity_id <= 0
                    or not isinstance(card_id, int) or card_id not in card_ids
                    or not isinstance(hp, (int, float)) or hp <= 0
                    or not isinstance(x, (int, float))
                    or not isinstance(y, (int, float))
                    or not self._on_own_half(action.owner, y)):
                continue
            anchor_distance_sq = (
                (float(x) - float(anchor[0])) ** 2
                + (float(y) - float(anchor[1])) ** 2
            )
            if anchor_distance_sq <= radius_sq:
                candidates.append((entity_id, float(x), float(y)))
        return frozenset(int(entity_id) for entity_id, _, _ in candidates)

    def _reservation_still_suppresses(
            self, reservation, state, now, matched_threat_ids=None):
        # A provisional reservation means the original touch still has no
        # terminal ACK outcome. Do not infer "it failed to solve the threat"
        # from enemy HP/count while telemetry is still deciding whether the
        # play even landed. This is the live over-defence failure mode seen
        # when a second/third card is queued before the first defender ACKs.
        if reservation.confidence == 'provisional':
            return True, 'awaiting_ack', 1.0

        # After accepted/timeout outcome, judge only on a genuinely newer
        # snapshot and only after a short effect-observation grace measured
        # from that outcome (not from the earlier input-complete time).
        received_at = float(getattr(state, 'received_at', 0.0) or 0.0)
        if (received_at <= reservation.reaction_started_at
                or now < reservation.suppress_until):
            return True, 'reaction_pending', 1.0

        count, hp = self._threat_metrics(
            state, matched_threat_ids or reservation.threat_ids)
        if count <= 0:
            return False, 'cohort_cleared', 0.0

        if reservation.baseline_count <= 1:
            residual_ratio = (
                hp / reservation.baseline_hp
                if reservation.baseline_hp > 0 else 1.0
            )
        else:
            count_ratio = count / max(1, reservation.baseline_count)
            hp_ratio = (
                hp / reservation.baseline_hp
                if reservation.baseline_hp > 0 else count_ratio
            )
            # Multiple surviving bodies can still threaten a tower even when
            # each has lost substantial HP, so preserve the larger signal.
            residual_ratio = max(count_ratio, hp_ratio)

        if residual_ratio >= self.THREAT_RESIDUAL_RELEASE_RATIO:
            return False, 'residual_still_dangerous', residual_ratio

        # A mostly handled cohort gets only a small finishing grace. It is not
        # considered solved forever: if a survivor is still worth defending
        # after this bounded grace, a fresh policy decision may spend again.
        if now < (
                reservation.suppress_until
                + self.THREAT_MOSTLY_HANDLED_GRACE_SECONDS):
            return True, 'residual_mostly_handled', residual_ratio
        return False, 'residual_grace_elapsed', residual_ratio

    def _matching_threat_reservation(self, action, state):
        now = time.perf_counter()
        self._prune_threat_reservations(state, now)
        threat_ids = self._nearby_threat_ids(action, state)
        if not threat_ids:
            return None, threat_ids
        current_group = self._threat_group_for_action(
            action, state)
        for reservation in reversed(self.threat_reservations):
            if reservation.owner != action.owner:
                continue
            if (
                current_group is not None
                and getattr(
                    reservation, 'threat_group_id', None
                ) is not None
                and not self._same_threat_group(
                    reservation, current_group)
            ):
                continue
            matched_ids = threat_ids & reservation.threat_ids
            if not matched_ids:
                matched_ids = self._rebound_threat_ids(
                    action, state, reservation, threat_ids)
            if not matched_ids:
                continue

            budget = self._defense_budget_context(action, state)
            if budget is not None:
                projected_defense = (
                    budget['committed_defense']
                    + budget['candidate_cost']
                )
                if projected_defense <= budget['budget_limit']:
                    self.log(
                        'threat_reservation_budget_released',
                        command_seq=reservation.command_seq,
                        card=reservation.card_id,
                        threat_ids=sorted(matched_ids),
                        attack_budget=round(budget['attack_budget'], 2),
                        committed_defense=round(
                            budget['committed_defense'], 2),
                        candidate_cost=round(
                            budget['candidate_cost'], 2),
                        projected_defense=round(
                            projected_defense, 2),
                        budget_limit=round(budget['budget_limit'], 2),
                        remaining_before_action=round(
                            budget['remaining_before_action'], 2),
                        threat_group_id=budget.get(
                            'threat_group_id'),
                        threat_group_lane=budget.get(
                            'threat_group_lane'),
                    )
                    return None, threat_ids

                self.log(
                    'threat_reservation_budget_exhausted',
                    command_seq=reservation.command_seq,
                    card=reservation.card_id,
                    threat_ids=sorted(matched_ids),
                    attack_budget=round(budget['attack_budget'], 2),
                    committed_defense=round(
                        budget['committed_defense'], 2),
                    candidate_cost=round(
                        budget['candidate_cost'], 2),
                    projected_defense=round(
                        projected_defense, 2),
                    budget_limit=round(budget['budget_limit'], 2),
                    threat_group_id=budget.get(
                        'threat_group_id'),
                    threat_group_lane=budget.get(
                        'threat_group_lane'),
                )
                return reservation, matched_ids

            suppress, reason, residual_ratio = (
                self._reservation_still_suppresses(
                    reservation, state, now, matched_ids))
            if suppress:
                return reservation, matched_ids
            # The first answer has had time to take effect and a newer frame
            # still shows a substantial residual threat. Let the policy's
            # newly computed defensive action through instead of treating the
            # whole cohort as permanently solved.
            self.threat_reservations.remove(reservation)
            self.log(
                'threat_reservation_recheck_released',
                command_seq=reservation.command_seq,
                card=reservation.card_id,
                threat_ids=sorted(reservation.threat_ids),
                reason=reason,
                residual_ratio=round(residual_ratio, 3),
            )
            return None, threat_ids
        return None, threat_ids

    def _commit_threat_reservation(self, pending, state, now, *, confidence='confirmed'):
        if not pending.threat_ids or pending.threat_target is None:
            return False
        live_ids = self._live_entity_ids(state)
        threat_ids = frozenset(pending.threat_ids & live_ids)
        if not threat_ids:
            return False
        ttl = {
            'provisional': self.THREAT_RESERVATION_PROVISIONAL_SECONDS,
            'confirmed': self.THREAT_RESERVATION_CONFIRMED_SECONDS,
            'uncertain': self.THREAT_RESERVATION_UNCERTAIN_SECONDS,
        }.get(confidence, self.THREAT_RESERVATION_CONFIRMED_SECONDS)

        # Do not let provisional protection expire while the same card is
        # still legitimately waiting for its hand/cycle ACK. This closes the
        # duplicate-defence gap seen on slow telemetry.
        if confidence == 'provisional':
            ack_budget = float(
                getattr(pending, 'ack_timeout_seconds', 0.0) or 0.0)
            ttl = max(
                ttl,
                ack_budget + self.THREAT_PROVISIONAL_ACK_GRACE_SECONDS,
            )

        existing = next((
            row for row in self.threat_reservations
            if row.command_seq == pending.command_seq
        ), None)
        if existing is not None:
            baseline_count = existing.baseline_count
            baseline_hp = existing.baseline_hp
        else:
            baseline_count, baseline_hp = self._threat_metrics(
                state, threat_ids)
        threat_card_ids, threat_anchor = self._threat_signature(
            state, threat_ids)
        if existing is not None:
            threat_card_ids = (threat_card_ids
                               or getattr(existing, 'threat_card_ids', frozenset()))
            threat_anchor = (threat_anchor
                             or getattr(existing, 'threat_anchor', None))

        if confidence == 'provisional':
            reaction_started_at = float(
                getattr(pending, 'input_completed_at', 0.0)
                or getattr(pending, 'sent_at', 0.0)
                or now
            )
            suppress_until = (
                reaction_started_at + self.THREAT_REACTION_HOLD_SECONDS
            )
        else:
            # ACK/timeout is the earliest point at which it is meaningful to
            # start waiting for the submitted card's battlefield effect.
            # Preserve the original threat baseline, but reset the observation
            # clock to this outcome so a slow ACK cannot consume the whole
            # reaction window before the first card has visibly acted.
            reaction_started_at = now
            card_family = int(pending.action.card_id or 0) // 1_000_000
            if confidence == 'uncertain':
                effect_grace = self.THREAT_POST_TIMEOUT_GRACE_SECONDS
            elif card_family == 28:
                effect_grace = self.THREAT_POST_ACK_SPELL_GRACE_SECONDS
            else:
                effect_grace = self.THREAT_POST_ACK_DEPLOY_GRACE_SECONDS
            suppress_until = now + effect_grace

        # Keep the bookkeeping row alive long enough to perform the
        # residual-threat recheck after both the reaction hold and the short
        # mostly-handled grace.  Suppression itself is still bounded by those
        # two clocks; this only prevents expiry from silently bypassing the
        # explicit recheck/release path at the exact boundary.
        expires_at = max(
            now + ttl,
            suppress_until + self.THREAT_MOSTLY_HANDLED_GRACE_SECONDS + 0.05,
        )
        budget = self._defense_budget_context(pending.action, state)
        threat_group = self._threat_group_for_action(
            pending.action, state)
        reservation = ThreatReservation(
            command_seq=pending.command_seq,
            owner=int(pending.action.owner),
            card_id=int(pending.action.card_id or 0),
            threat_ids=threat_ids,
            target=pending.threat_target,
            expires_at=expires_at,
            confidence=confidence,
            reaction_started_at=reaction_started_at,
            suppress_until=suppress_until,
            baseline_count=baseline_count,
            baseline_hp=baseline_hp,
            threat_card_ids=threat_card_ids,
            threat_anchor=threat_anchor,
            defense_cost=float(pending.cost),
            attack_budget=(
                float(budget['attack_budget'])
                if budget is not None else 0.0
            ),
            threat_group_id=(
                pending.threat_group_id
                or (
                    threat_group['group_id']
                    if threat_group is not None else None
                )
            ),
            threat_group_lane=(
                pending.threat_group_lane
                or (
                    threat_group['lane']
                    if threat_group is not None else None
                )
            ),
        )
        self.threat_reservations[:] = [
            row for row in self.threat_reservations
            if row.command_seq != pending.command_seq
        ]
        self.threat_reservations.append(reservation)
        self.log('threat_reservation_started',
                 command_seq=pending.command_seq,
                 card=pending.action.card_id,
                 threat_ids=sorted(threat_ids),
                 target_world=list(pending.threat_target),
                 confidence=confidence,
                 ttl_ms=round((expires_at - now) * 1000),
                 suppress_ms=max(
                     0, round((suppress_until - now) * 1000)),
                 baseline_count=baseline_count,
                 baseline_hp=round(baseline_hp, 1),
                 defense_cost=round(float(pending.cost), 2),
                 attack_budget=(
                     round(float(budget['attack_budget']), 2)
                     if budget is not None else None),
                 threat_card_ids=sorted(threat_card_ids),
                 threat_anchor=(list(threat_anchor)
                                if threat_anchor is not None else None),
                 threat_group_id=reservation.threat_group_id,
                 threat_group_lane=reservation.threat_group_lane,
                 threat_group_attack_cost=(
                     round(float(budget['attack_budget']), 2)
                     if budget is not None else None),
                 threat_group_assigned_defense_cost=(
                     round(float(
                         budget['committed_defense']), 2)
                     if budget is not None else None))
        return True

    def pause(self):
        # Drop stale plans, retain sent actions for ACK reconciliation on resume.
        for pending in list(self.pending):
            if pending.state == 'queued':
                self.pending.remove(pending)
                self.log('action_cancelled', reason='telemetry_paused',
                         card=pending.action.card_id, decision_tick=pending.decision_tick)

    def end_battle(self):
        for pending in self.pending:
            self.log('action_cancelled' if pending.state == 'queued' else 'action_unresolved_at_terminal',
                     reason='battle_finalized', card=pending.action.card_id,
                     decision_tick=pending.decision_tick, status=pending.state)
        for pending in self.ack_watch:
            self.log('action_unresolved_at_terminal',
                     reason='battle_finalized', card=pending.action.card_id,
                     decision_tick=pending.decision_tick, status='ack_watch',
                     command_seq=pending.command_seq)
        self.reset()

    def _raw_player(self, state, owner=None):
        if state is None:
            return None
        target_owner = state.local_owner if owner is None else owner
        return next(
            (p for p in state.raw.get('players', [])
             if int(p.get('owner', -1)) == int(target_owner)),
            None,
        )

    def _raw_hand_card(self, state, slot, owner=None):
        player = self._raw_player(state, owner)
        if player is None:
            return None
        for row in player.get('hand', []):
            if int(row.get('slot', -1)) == int(slot):
                return max(0, int(row.get('card_id', 0)))
        return 0

    def _authoritative_hand_card(self, state, slot, owner=None):
        """Return raw hand telemetry unless the test/state explicitly differs.

        Production BattleState.hand_cards is parsed from the same raw snapshot,
        so a difference only exists for our cycle overlay or a deliberately
        constructed test state. Never let our own overlay count as native hand
        rotation evidence.
        """
        raw = self._raw_hand_card(state, slot, owner)
        if state is None or slot is None:
            return raw
        slot = int(slot)
        if slot in self.slot_hand_overrides:
            return raw
        if 0 <= slot < len(state.hand_cards):
            visible = int(state.hand_cards[slot])
            if raw is None or visible != int(raw):
                return visible
        return raw

    def _native_cycle(self, state, owner=None):
        player = self._raw_player(state, owner)
        if player is None:
            return None
        raw = player.get('cycle')
        if raw is None:
            return None
        try:
            cycle = tuple(int(card) for card in raw)
        except (TypeError, ValueError):
            return None
        if len(cycle) != 4 or len(set(cycle)) != 4:
            return None
        return cycle

    @staticmethod
    def _expected_cycle_after_play(prior_cycle, card_id):
        if prior_cycle is None or len(prior_cycle) != 4:
            return None
        return tuple(prior_cycle[1:]) + (int(card_id),)

    def _cycle_confirms_play(self, pending, state):
        current = self._native_cycle(state, pending.action.owner)
        expected = self._expected_cycle_after_play(
            getattr(pending, 'prior_cycle', None), pending.action.card_id)
        return expected is not None and current == expected

    def _infer_slot_card_from_cycle(self, state, slot):
        """Infer one stale slot only when deck/cycle/other slots force it."""
        if state is None or self.slot_hand_overrides.keys() - {int(slot)}:
            return None
        cycle = self._native_cycle(state)
        deck = tuple(int(card) for card in state.deck_cards)
        if cycle is None or len(deck) != 8 or len(set(deck)) != 8:
            return None
        other = []
        for other_slot in range(4):
            if other_slot == int(slot):
                continue
            card = self._raw_hand_card(state, other_slot)
            if card is None or card <= 0:
                return None
            other.append(int(card))
        if len(set(other)) != 3 or set(other) & set(cycle):
            return None
        candidates = set(deck) - set(cycle) - set(other)
        if len(candidates) != 1:
            return None
        card = next(iter(candidates))
        return card if card > 0 else None

    def _apply_slot_hand_overrides(self, state):
        if state is None:
            return
        for slot, override in list(self.slot_hand_overrides.items()):
            raw_card = self._raw_hand_card(state, slot)
            stale_card = int(override['stale_card'])
            if raw_card is None:
                override['valid'] = False
                continue
            if int(raw_card) != stale_card:
                del self.slot_hand_overrides[slot]
                state.hand_cards[slot] = int(raw_card)
                self.log('slot_hand_override_cleared',
                         command_seq=override['command_seq'],
                         slot=slot,
                         stale_card=stale_card,
                         replacement_card=override.get('card_id'),
                         reason='native_hand_caught_up')
                continue
            inferred = self._infer_slot_card_from_cycle(state, slot)
            if inferred is None or inferred == stale_card:
                override['valid'] = False
                continue
            previous = override.get('card_id')
            override['card_id'] = int(inferred)
            override['valid'] = True
            state.hand_cards[slot] = int(inferred)
            if previous is not None and int(previous) != int(inferred):
                self.log('slot_hand_override_advanced',
                         command_seq=override['command_seq'],
                         slot=slot,
                         previous_card=int(previous),
                         replacement_card=int(inferred),
                         evidence='native_cycle_hand_partition')

    def _recover_slot_override(self, state, slot, stale_card, command_seq,
                               replacement_card=None, evidence='native_cycle_hand_partition'):
        if replacement_card is None:
            replacement_card = self._infer_slot_card_from_cycle(state, slot)
        if replacement_card is None or int(replacement_card) == int(stale_card):
            return False
        self.slot_hand_overrides[int(slot)] = {
            'stale_card': int(stale_card),
            'card_id': int(replacement_card),
            'command_seq': int(command_seq),
            'valid': True,
        }
        state.hand_cards[int(slot)] = int(replacement_card)
        self.log('slot_consume_guard_recovered',
                 command_seq=command_seq,
                 slot=slot,
                 stale_card=int(stale_card),
                 replacement_card=int(replacement_card),
                 evidence=evidence,
                 slot_remains_blocked=False)
        return True

    def _start_slot_consume_guard(self, pending, now, evidence):
        slot = pending.action.hand_slot
        if slot is None:
            return
        soft_expires_at = float(now) + float(config.ELIXIR_RESERVATION_SECONDS)
        hard_expires_at = float(now) + float(config.SLOT_CONSUME_GUARD_MAX_SECONDS)
        self.slot_consume_guards[int(slot)] = {
            'card_id': int(pending.action.card_id or 0),
            'raw_baseline_card': int(
                getattr(pending, 'prior_raw_hand_card', None)
                if getattr(pending, 'prior_raw_hand_card', None) is not None
                else (pending.action.card_id or 0)
            ),
            'command_seq': int(pending.command_seq),
            'evidence': str(evidence),
            'soft_expires_at': soft_expires_at,
            'hard_expires_at': hard_expires_at,
            'extension_logged': False,
            'stale_logged': False,
        }
        self.log('slot_consume_guard_started',
                 command_seq=pending.command_seq,
                 card=pending.action.card_id,
                 slot=slot,
                 evidence=evidence,
                 ttl_ms=round(config.ELIXIR_RESERVATION_SECONDS * 1000),
                 max_ttl_ms=round(config.SLOT_CONSUME_GUARD_MAX_SECONDS * 1000))

    def _prune_slot_consume_guards(self, state, now=None):
        if state is None:
            return
        if now is None:
            now = time.perf_counter()
        self._apply_slot_hand_overrides(state)
        for slot, guard in list(self.slot_consume_guards.items()):
            card_id = int(guard['card_id'])
            raw_baseline_card = int(guard.get('raw_baseline_card', card_id))
            raw_card = self._authoritative_hand_card(state, slot)
            rotated = (
                raw_card is not None
                and int(raw_card) != raw_baseline_card
            )
            soft_expired = now >= float(guard['soft_expires_at'])
            hard_expired = now >= float(guard['hard_expires_at'])
            if rotated:
                del self.slot_consume_guards[slot]
                self._clear_spend(int(guard['command_seq']))
                self.log('slot_consume_guard_cleared',
                         command_seq=guard['command_seq'],
                         card=card_id,
                         slot=slot,
                         evidence=guard['evidence'],
                         reason='hand_rotation')
                continue
            inferred = self._infer_slot_card_from_cycle(state, slot)
            if inferred is not None and inferred != card_id:
                del self.slot_consume_guards[slot]
                self._clear_spend(int(guard['command_seq']))
                if inferred == raw_baseline_card:
                    # The exact cycle partition now agrees with the unchanged
                    # raw slot, so no overlay is required even though the
                    # weak-ACK source card differed from that stale baseline.
                    self.slot_hand_overrides.pop(slot, None)
                    state.hand_cards[slot] = int(raw_baseline_card)
                    self.log('slot_consume_guard_cleared',
                             command_seq=guard['command_seq'],
                             card=card_id,
                             slot=slot,
                             evidence=guard['evidence'],
                             reason='native_cycle_reconciled')
                    continue
                if self._recover_slot_override(
                        state, slot, raw_baseline_card, guard['command_seq'],
                        replacement_card=inferred):
                    continue
            if not soft_expired:
                continue
            if not hard_expired:
                if not guard.get('extension_logged'):
                    guard['extension_logged'] = True
                    self.log('slot_consume_guard_extended',
                             command_seq=guard['command_seq'],
                             card=card_id,
                             slot=slot,
                             evidence=guard['evidence'],
                             remaining_ms=round(
                                 max(0.0, float(guard['hard_expires_at']) - now) * 1000))
                continue
            # The positive ACK proved the card was consumed even though the
            # hand snapshot is still stale. Timeout alone never reopens that
            # exact native slot/card; only authoritative hand rotation or a
            # unique native cycle/other-hand partition may recover it. The
            # extra virtual spend reservation itself stays bounded so unrelated
            # slots can keep using the live elixir value.
            self._clear_spend(int(guard['command_seq']))
            if not guard.get('stale_logged'):
                guard['stale_logged'] = True
                self.log('slot_consume_guard_stale',
                         command_seq=guard['command_seq'],
                         card=card_id,
                         slot=slot,
                         evidence=guard['evidence'],
                         age_ms=round(
                             config.SLOT_CONSUME_GUARD_MAX_SECONDS * 1000),
                         slot_remains_blocked=True)

    def blocked_slots(self, state):
        blocked = {p.action.hand_slot for p in (*self.pending, *self.ack_watch, *self.spawn_watch)
                   if p.action.hand_slot is not None}
        now = time.perf_counter()
        self._prune_slot_consume_guards(state, now)
        blocked.update(self.slot_consume_guards)
        blocked.update(
            slot for slot, override in self.slot_hand_overrides.items()
            if not override.get('valid')
        )
        for slot, (card, until) in list(self.cooldowns.items()):
            if state.hand_cards[slot] != card or now >= until:
                del self.cooldowns[slot]
            else:
                blocked.add(slot)
        if self.fault:
            blocked.update(range(4))
        return blocked

    def blocked_abilities(self):
        return self.ability_locks | {p.action.source_entity
                                    for p in (*self.pending, *self.ack_watch, *self.spawn_watch)
                                    if p.action.kind.value == 'activate_ability'}

    @property
    def reserved_elixir(self):
        # Queued actions have not touched Android yet and therefore need an
        # explicit reservation. Once an action is sent, its cost moves into
        # unconfirmed_spend. Counting sent pending rows here as well would
        # double-reserve the same card while the touch worker is still busy.
        queued = sum(
            p.cost for p in self.pending
            if getattr(p, 'state', 'queued') == 'queued'
        )
        # spawn_watch is retained for legacy post-ACK observation tracking. If
        # a row is ever present there without a matching spend reservation,
        # keep its cost protected exactly once.
        spend_seqs = {int(seq) for _, _, seq in self.unconfirmed_spend}
        spawn_only = sum(
            p.cost for p in self.spawn_watch
            if int(p.command_seq) not in spend_seqs
        )
        return queued + spawn_only + sum(
            cost for _, cost, _ in self.unconfirmed_spend)

    def _prune_unconfirmed_spend(self, now):
        # Never let the age-based safety TTL expire while the command is still
        # actively waiting for input completion/ACK/hand reconciliation.
        # CARD_ACK_TIMEOUT_MAX_SECONDS can exceed the old reservation TTL once
        # emulator/probe telemetry is slow, so age alone is no longer enough.
        active_seqs = {
            int(p.command_seq)
            for p in self.pending
            if getattr(p, 'state', 'queued') == 'sent'
        }
        active_seqs.update(int(p.command_seq) for p in self.ack_watch)
        active_seqs.update(int(p.command_seq) for p in self.spawn_watch)
        active_seqs.update(
            int(guard['command_seq'])
            for guard in self.slot_consume_guards.values()
            if now < float(guard['hard_expires_at'])
        )
        self.unconfirmed_spend[:] = [
            row for row in self.unconfirmed_spend
            if int(row[2]) in active_seqs
            or now - row[0] < config.ELIXIR_RESERVATION_SECONDS
        ]

    def _clear_spend(self, command_seq):
        self.unconfirmed_spend[:] = [row for row in self.unconfirmed_spend
                                     if row[2] != command_seq]

    def _drop_prediction(self, command_seq):
        """Remove only the speculative unit for one unconfirmed input."""
        self.predictions[:] = [prediction for prediction in self.predictions
                               if prediction.get('command_seq') != command_seq]

    def _retain_uncertain_prediction(self, command_seq, now):
        """Keep only a short-lived visual prediction after an ACK timeout."""
        for prediction in self.predictions:
            if prediction.get('command_seq') == command_seq:
                prediction['uncertain'] = True
                prediction['expires_at'] = now + config.UNCERTAIN_PREDICTION_SECONDS
                return True
        return False

    def model_predictions(self, state):
        """Return short-lived, model-only predictions for submitted cards."""
        if not config.ENABLE_MODEL_PREDICTION_OVERLAY:
            self.predictions.clear()
            return ()
        now = time.perf_counter()
        self.predictions[:] = [p for p in self.predictions if now < p['expires_at']]
        real = tuple(state.entities) if state is not None else ()
        kept = []
        for prediction in self.predictions:
            action = prediction['action']
            # Hero abilities are button taps and have no ground target or
            # deployable entity. They must never enter the unit overlay.
            if action.kind.value != 'play_card' or action.target_grid is None:
                continue
            target = action_world(action)
            matched = any(e.get('owner') == action.owner and e.get('card_id') == action.card_id
                          and (e.get('x', target[0]) - target[0]) ** 2
                          + (e.get('y', target[1]) - target[1]) ** 2 <= 1800 ** 2
                          for e in real)
            if not matched:
                kept.append(prediction)
        self.predictions[:] = kept
        return tuple({'id': -int(p['command_seq']), 'owner': p['action'].owner,
                      'card_id': p['action'].card_id, 'x': target[0], 'y': target[1],
                      'predicted': True, 'command_seq': p['command_seq'],
                      'age_ms': max(0.0, (now - float(p.get('sent_at', now))) * 1000.0),
                      'latency_ms': self.end_to_end_latency_ms}
                     for p in kept for target in (action_world(p['action']),))

    def submit(self, decoded, state):
        if getattr(state, 'native_finalized', False) is True:
            self.log('action_rejected', reason='battle_finalized')
            return
        for action in decoded.actions:
            if action.kind.value == 'wait':
                continue
            if self.fault:
                self.log('action_rejected', reason='execution_fault', action=action.to_dict())
                continue
            if self.max_actions is not None and self.attempted_actions >= self.max_actions:
                self.log('action_rejected', reason='action_budget_reached', action=action.to_dict(),
                         max_actions=self.max_actions)
                continue
            if self._in_flight_count() >= self.MAX_IN_FLIGHT_ACTIONS:
                self.log('action_rejected', reason='in_flight_capacity', action=action.to_dict(),
                         capacity=self.MAX_IN_FLIGHT_ACTIONS)
                # One serialized input is already in flight. The remaining
                # actions belong to the same model decision and must not be
                # retried in a tight loop; the next decision will use fresh
                # hand/elixir/scene state.
                break
            skill = action.kind.value == 'activate_ability'
            if action.kind.value not in ('play_card', 'activate_ability'):
                self.log('unsupported_action', action=action.to_dict())
                continue
            slot = action.hand_slot
            if skill:
                row = raw_controller(state, action)
                if (action.owner != state.local_owner or action.ability_id != ABILITY or self.fault
                    or action.target_kind.value != 'none' or action.source_entity in self.blocked_abilities()
                    or not row or row.get('button_state') not in (2, 4) or row.get('charges') != 1
                    or row.get('cooldown_ms') != 0 or row.get('max_charges') != 1):
                    self.log('action_rejected', reason='ability_changed_or_locked', action=action.to_dict())
                    continue
                cost = 3.0  # verified Musketeer_hero_Ability contract only
            else:
                cost = float(action.metadata['policy_effective_cost'])
            if not skill and (slot is None or slot in self.blocked_slots(state) or state.hand_cards[slot] != action.card_id):
                self.log('action_rejected', reason='slot_changed_or_locked', action=action.to_dict())
                continue
            miss_until = self._recent_misses.get(self._action_key(action), 0.0)
            if not skill and time.perf_counter() < miss_until:
                self.log('action_suppressed', reason='recent_miss_same_target',
                         action=action.to_dict(), remaining_ms=(miss_until-time.perf_counter())*1000)
                continue
            threat_ids = frozenset()
            threat_target = None
            threat_group_id = None
            threat_group_lane = None
            if not skill:
                reservation, threat_ids = self._matching_threat_reservation(action, state)
                if reservation is not None:
                    now = time.perf_counter()
                    self.log('action_suppressed', reason='threat_already_committed',
                             action=action.to_dict(), threat_ids=sorted(threat_ids),
                             committed_by=reservation.command_seq,
                             remaining_ms=max(0.0, (reservation.expires_at-now)*1000.0))
                    continue
                if threat_ids:
                    threat_target = action_world(action)
                    threat_group = self._threat_group_for_action(
                        action, state)
                    if threat_group is not None:
                        threat_group_id = threat_group['group_id']
                        threat_group_lane = threat_group['lane']
            if state.elixir - self.reserved_elixir < cost:
                self.log('action_rejected', reason='reserved_elixir', action=action.to_dict(),
                         elixir=state.elixir, reserved_elixir=self.reserved_elixir,
                         required_cost=cost, available_elixir=state.elixir - self.reserved_elixir)
                continue
            due = state.received_at + action.execute_offset_ticks * config.TICK_SECONDS
            pending = PendingAction(action, state.tick, due, due + config.ACTION_MAX_LATENESS_SECONDS,
                cost, command_seq=self._next_command_seq, decision_at=time.perf_counter(),
                threat_ids=threat_ids, threat_target=threat_target,
                threat_group_id=threat_group_id,
                threat_group_lane=threat_group_lane)
            pending.observation_received_at = state.received_at
            self._next_command_seq += 1
            if self.dry_run:
                self.log('dry_run_action', action=action.to_dict(),
                    screen=self.actuator.ability_screen(action) if skill else self.actuator.calibration.action_to_screen(action),
                    world=None if skill else action_world(action))
            else:
                self.pending.append(pending)
                self.log('action_queued', action=action.to_dict(), decision_tick=state.tick,
                         command_seq=pending.command_seq)
                # Touch selection and placement share one UI transaction.
                # Accept only the first actionable item from a decoded batch;
                # never queue a second card from the same stale observation.
                if len(decoded.actions) > 1:
                    self.log('action_rejected', reason='in_flight_capacity',
                             action=decoded.actions[1].to_dict(),
                             capacity=self.MAX_IN_FLIGHT_ACTIONS,
                             suppressed_batch=True)
                break

    def poll(self, state, validate):
        now = time.perf_counter()
        self._prune_unconfirmed_spend(now)
        if self.future is not None and self.future.done():
            completed_at = time.perf_counter()
            try:
                result = self.future.result()
                end_to_end_ms = max(0.0, (completed_at - self.active.decision_at) * 1000.0)
                self._latency_samples_ms.append(end_to_end_ms)
                # A single slow ADB/emulator frame must not move the model's
                # forecast hundreds of milliseconds into the future.  Use a
                # recent median for timing alignment; the current action's
                # measured latency is still logged independently.
                self._latency_samples_ms[:] = self._latency_samples_ms[-8:]
                ordered = sorted(self._latency_samples_ms)
                middle = len(ordered) // 2
                if len(ordered) % 2:
                    robust_latency = ordered[middle]
                else:
                    robust_latency = (ordered[middle - 1] + ordered[middle]) / 2.0
                self.end_to_end_latency_ms = max(50.0, min(350.0, robust_latency))
                self.log('input_completed', card=self.active.action.card_id,
                         ability=self.active.action.ability_id,
                         command_seq=self.active.command_seq,
                         end_to_end_latency_ms=end_to_end_ms,
                         observation_to_input_completed_ms=(
                             (completed_at-self.active.observation_received_at)*1000
                             if self.active.observation_received_at else None),
                         prediction_compensation_ms=self.end_to_end_latency_ms,
                         **result)
                # The Android shell/touch transport can occasionally take
                # longer than the nominal ACK window.  The game cannot have
                # consumed a tap before that transport completes, so start
                # ACK timing here rather than at thread submission.  This
                # prevents a slow but still-live touch from being mislabeled
                # UNKNOWN halfway through its own input transaction.
                completed = self.active
                completed.input_completed_at = completed_at
                completed.ack_timeout_seconds = (
                    float(config.ACK_TIMEOUT_SECONDS)
                    if completed.action.kind.value == 'activate_ability'
                    else self._card_ack_timeout_seconds()
                )
                if completed in self.pending:
                    self.pending.remove(completed)
                if completed not in self.ack_watch:
                    self.ack_watch.append(completed)
                if (state is not None
                        and completed.action.kind.value == 'play_card'):
                    self._commit_threat_reservation(
                        completed, state, completed_at, confidence='provisional')
                self._fresh_state_required = True
                self.log('ack_watch_started',
                         command_seq=completed.command_seq,
                         card=completed.action.card_id,
                         slot=completed.action.hand_slot,
                         watches=len(self.ack_watch),
                         timeout_ms=round(completed.ack_timeout_seconds * 1000))
            except Exception as exc:
                self.fault = str(exc)
                self.pending.clear()
                self.log('input_fault', error=self.fault)
            self.future, self.active = None, None
            # Future completion may happen after the poll's initial timestamp.
            # Refresh monotonic time before reconciling older ACK watches.
            now = time.perf_counter()
        if state is None:
            # A transient query failure must not launch any queued touch.
            return
        if self.future is not None:
            # Never inspect hand/elixir timeout rules while the serial touch
            # transaction is still executing.  In particular, do not let the
            # the ACK budget race a slow emulator input operation.
            return
        if getattr(state, 'native_finalized', False) is True:
            self.end_battle()
            return
        self._prune_slot_consume_guards(state, now)
        for pending in list(self.pending):
            if pending.state == 'sent' and self.future is None:
                self.pending.remove(pending)
                if pending not in self.ack_watch:
                    self.ack_watch.append(pending)
        for pending in list(self.ack_watch):
            action = pending.action
            skill = action.kind.value == 'activate_ability'
            if pending.state == 'sent':
                # Never ACK a touch from the snapshot that was captured before
                # that touch completed. Wait for an authoritative post-input
                # probe frame; otherwise an older elixir/hand transition can
                # be misattributed to this action.
                input_completed_at = float(
                    getattr(pending, 'input_completed_at', 0.0) or 0.0)
                ack_started_at = input_completed_at or pending.sent_at
                if (input_completed_at > 0
                        and state.received_at <= input_completed_at):
                    continue
                if skill:
                    row = raw_controller(state, action)
                    if state.tick > pending.sent_tick and row and row.get('charges') == 0:
                        self.ack_watch.remove(pending)
                        self._clear_spend(pending.command_seq)
                        self.log('ability_ack', ability=action.ability_id, source_entity=action.source_entity,
                                 tick=state.tick, latency_ms=(now-ack_started_at)*1000,
                                 input_start_to_ack_ms=(now-pending.sent_at)*1000,
                                 evidence='same_controller_carrier_charge_1_to_0')
                        self.confirmed_actions += 1
                        self._fresh_state_required = True
                        if self.on_ability_ack:
                            self.on_ability_ack(action, state)
                    elif now - ack_started_at > config.ACK_TIMEOUT_SECONDS:
                        self.ack_watch.remove(pending)
                        # An ambiguous ability tap must never be replayed, but
                        # it should not stop ordinary card play for the rest
                        # of the match.  Lock this carrier and let cards
                        # continue after recording UNKNOWN for the skill.
                        self.ability_locks.add(action.source_entity)
                        self.log('ability_ack_timeout', ability=action.ability_id,
                                 source_entity=action.source_entity, command_seq=pending.command_seq,
                                 outcome='unknown')
                    continue
                ack_timeout_seconds = float(
                    getattr(pending, 'ack_timeout_seconds', 0.0) or 0.0)
                if ack_timeout_seconds <= 0:
                    ack_timeout_seconds = self._card_ack_timeout_seconds()
                    pending.ack_timeout_seconds = ack_timeout_seconds
                raw_hand_card = self._authoritative_hand_card(
                    state, action.hand_slot, action.owner)
                prior_raw_hand_card = getattr(
                    pending, 'prior_raw_hand_card', None)
                hand_baseline = (
                    int(prior_raw_hand_card)
                    if prior_raw_hand_card is not None
                    else int(action.card_id)
                )
                hand_changed = (
                    state.tick > pending.sent_tick
                    and raw_hand_card is not None
                    and int(raw_hand_card) != hand_baseline
                )
                cycle_changed = (
                    state.tick > pending.sent_tick
                    and self._cycle_confirms_play(pending, state)
                )

                # Troops/buildings can provide a second, strictly positive ACK
                # signal: a new own entity from the submitted source card that
                # did not exist before the input. Missing this signal never
                # proves failure, but seeing it proves the deploy reached the
                # game even when hand/elixir telemetry is late.
                card_family = int(action.card_id or 0) // 1_000_000
                spawn_ack = False
                spawn_entity_id = None
                spawn_ack_evidence = None
                if card_family in (26, 27):
                    evolved_play = (
                        action.card_id in BINDINGS
                        and action.metadata.get('policy_effective_form_code') == 1
                    )
                    hero_musketeer_play = (
                        action.card_id == MUSKETEER
                        and action.metadata.get('policy_effective_form_code') == 2
                    )
                    prior_entities = getattr(
                        pending, 'prior_entities', frozenset()) or frozenset()
                    hero_members = set()
                    if hero_musketeer_play:
                        player = next(
                            (p for p in state.raw.get('players', [])
                             if p.get('owner') == action.owner),
                            None,
                        )
                        if player:
                            hero_members = {
                                eid for row in player.get('ability_runtime', [])
                                if row.get('known') is True
                                and row.get('ability_name') == ABILITY
                                for eid in row.get('members', [])
                            }

                    new_own_entities = []
                    for entity in state.entities:
                        entity_id = entity.get('id')
                        if not isinstance(entity_id, int) or entity_id in prior_entities:
                            continue
                        if entity.get('owner') != action.owner:
                            continue
                        new_own_entities.append(entity)
                        if evolved_play:
                            matches = is_evolved_entity(entity, action.card_id)
                        elif hero_musketeer_play:
                            matches = (
                                entity.get('card_id') == 203000014
                                and entity_id in hero_members
                            )
                        else:
                            matches = entity.get('card_id') == action.card_id
                        if matches:
                            spawn_ack = True
                            spawn_entity_id = entity_id
                            spawn_ack_evidence = 'new_source_entity'
                            break

                    # Native entity card IDs can represent the spawned unit
                    # rather than the deck/source card (multi-body troops and
                    # transformed forms are common examples).  When exactly
                    # one card is awaiting ACK, a brand-new own entity that
                    # appears very close to the submitted deploy point is
                    # still strong positive evidence that this touch landed.
                    # Never use this fallback for spells or with competing ACK
                    # watches, because either case makes attribution ambiguous.
                    if (not spawn_ack and len(self.ack_watch) == 1
                            and action.target_grid is not None):
                        target_x, target_y = action_world(action)
                        nearby = []
                        for entity in new_own_entities:
                            ex, ey = entity.get('x'), entity.get('y')
                            if not isinstance(ex, (int, float)) or not isinstance(ey, (int, float)):
                                continue
                            distance2 = (float(ex) - target_x) ** 2 + (float(ey) - target_y) ** 2
                            if distance2 <= 2200.0 ** 2:
                                nearby.append((distance2, entity))
                        if nearby:
                            _, nearest = min(nearby, key=lambda row: row[0])
                            spawn_ack = True
                            spawn_entity_id = nearest.get('id')
                            spawn_ack_evidence = 'new_own_entity_near_target'
                # Some probe revisions publish elixir before hand rotation.
                # Treat a sufficiently large, near-immediate cost drop as a
                # fallback ACK.  Natural regeneration cannot satisfy this
                # downward threshold, and the original hand check remains
                # authoritative whenever it is available.
                elixir_changed = False
                # If any earlier action still lacks authoritative hand
                # reconciliation, a new aggregate elixir drop is not uniquely
                # attributable. This includes weak positive ACK guards and
                # timed-out/unresolved spend reservations. Keep the newer
                # action on ACK watch until a hand/spawn signal arrives.
                other_unconfirmed_spend = any(
                    int(command_seq) != int(pending.command_seq)
                    for _, _, command_seq in self.unconfirmed_spend
                )
                allow_elixir_fallback = (
                    len(self.ack_watch) == 1
                    and not self.slot_consume_guards
                    and not other_unconfirmed_spend
                )
                if (allow_elixir_fallback and pending.prior_elixir is not None
                        and state.elixir is not None):
                    elixir_changed = (state.tick > pending.sent_tick and
                        float(state.elixir) <= float(pending.prior_elixir) - pending.cost + 0.15)
                if hand_changed or cycle_changed or elixir_changed or spawn_ack:
                    self.ack_watch.remove(pending)
                    ack_evidence = (
                        'hand_rotation' if hand_changed else
                        'native_cycle_transition' if cycle_changed else
                        'elixir_cost_drop' if elixir_changed else
                        spawn_ack_evidence or 'new_source_entity'
                    )
                    if hand_changed:
                        self._clear_spend(pending.command_seq)
                    elif cycle_changed:
                        # Exact own-cycle progression is authoritative card
                        # consumption evidence. If the hand slot itself is
                        # still stale, recover its effective replacement from
                        # the pre-play next-card position instead of reopening
                        # the stale source card.
                        self._clear_spend(pending.command_seq)
                        prior_cycle = getattr(pending, 'prior_cycle', None)
                        prior_raw_hand_card = getattr(
                            pending, 'prior_raw_hand_card', None)
                        replacement = (
                            int(prior_cycle[0])
                            if prior_cycle else None
                        )
                        stale_raw = (
                            int(prior_raw_hand_card)
                            if prior_raw_hand_card is not None
                            else int(action.card_id)
                        )
                        if replacement == stale_raw:
                            self.slot_hand_overrides.pop(
                                int(action.hand_slot), None)
                            state.hand_cards[int(action.hand_slot)] = stale_raw
                        else:
                            self._recover_slot_override(
                                state, action.hand_slot, stale_raw,
                                pending.command_seq,
                                replacement_card=replacement,
                                evidence='native_cycle_transition')
                    else:
                        # Prevent the same stale native slot/card from being
                        # selected again on the very frame that supplied only
                        # a weak positive ACK. Other slots remain eligible.
                        self._start_slot_consume_guard(
                            pending, now, ack_evidence)
                        # An observed elixir drop already accounts for the
                        # spend in the live resource value. A spawn-only ACK
                        # does not, so keep its short-lived virtual spend until
                        # hand rotation/guard expiry reconciles the snapshot.
                        if elixir_changed:
                            self._clear_spend(pending.command_seq)
                    ack_latency_ms = (now - ack_started_at) * 1000
                    self._record_card_ack_latency(
                        ack_latency_ms, evidence=ack_evidence)
                    self.log('hand_ack', card=action.card_id, slot=action.hand_slot,
                        command_seq=pending.command_seq,
                        tick=state.tick, latency_ms=ack_latency_ms,
                        decision_to_ack_ms=(now-pending.decision_at)*1000,
                        input_to_ack_ms=ack_latency_ms,
                        input_start_to_ack_ms=(now-pending.sent_at)*1000,
                        ack_timeout_ms=round(ack_timeout_seconds * 1000),
                        outcome='accepted',
                        evidence=ack_evidence,
                        spawn_entity_id=spawn_entity_id)
                    if action.card_id in BINDINGS and action.metadata.get('policy_effective_form_code') == 1:
                        player = next(p for p in state.raw['players'] if p['owner'] == action.owner)
                        row = next((r for r in player.get('card_runtime', []) if r.get('card_id') == action.card_id), {})
                        if pending.prior_evolution_progress == BINDINGS[action.card_id].cycles and row.get('evolution_progress') == 0 and row.get('active_form') == 0:
                            self.log('evolution_ack', card=action.card_id, tick=state.tick,
                                evidence='hand_transition_and_native_cycle_2_to_0',
                                latency_ms=(now-ack_started_at)*1000,
                                input_start_to_ack_ms=(now-pending.sent_at)*1000)
                    # Hand rotation is the authoritative client-side
                    # consume acknowledgement.  A troop can spawn and die
                    # between two observations, and spells have no durable
                    # spawn entity at all; neither case should halt the
                    # entire continuous runner.
                    self.confirmed_actions += 1
                    self._confirmed_for_simulation.append((action, pending.sent_tick,
                                                           pending.command_seq))
                    self._fresh_state_required = True
                    if self._commit_threat_reservation(
                            pending, state, now, confidence='confirmed'):
                        pass
                    else:
                        self.log('post_action_settle_skipped',
                                 command_seq=pending.command_seq,
                                 card=action.card_id,
                                 reason='background_hand_ack')
                elif now - ack_started_at > ack_timeout_seconds:
                    # One completed card touch that reaches the ACK deadline
                    # without *any* consumption evidence gets exactly one
                    # second chance, but only after a newer authoritative
                    # probe frame. Keeping the row on ACK watch during this
                    # one-frame probe also lets a late hand/cycle transition
                    # win normally instead of being mistaken for a miss.
                    if (action.kind.value == 'play_card'
                            and getattr(pending, 'retry_count', 0) < 1
                            and (self.max_actions is None
                                 or self.attempted_actions < self.max_actions)):
                        def retry_due(row):
                            row_action = row.action
                            if (row_action.kind.value != 'play_card'
                                    or getattr(row, 'retry_count', 0) >= 1):
                                return False
                            row_started = (
                                row.input_completed_at or row.sent_at)
                            row_timeout = (
                                row.ack_timeout_seconds
                                or self._card_ack_timeout_seconds())
                            return now - row_started > row_timeout

                        retry_candidates = [
                            row for row in self.ack_watch
                            if retry_due(row)
                        ]
                        retry_leader = (
                            min(retry_candidates,
                                key=lambda row: row.command_seq)
                            if retry_candidates else pending
                        )
                        if retry_leader is not pending:
                            if not getattr(pending, 'retry_waiting', False):
                                pending.retry_waiting = True
                                self.log('action_retry_waiting',
                                         card=action.card_id,
                                         slot=action.hand_slot,
                                         command_seq=pending.command_seq,
                                         tick=state.tick,
                                         waiting_for=retry_leader.command_seq,
                                         reason='older_timed_out_retry')
                            continue

                        live_competitors = [
                            row for row in self.ack_watch
                            if row is not pending and not retry_due(row)
                        ]
                        # A previously selected retry may already have moved
                        # from ACK watch back into the serial input queue. Do
                        # not arm the next timed-out card against a baseline
                        # that predates that retry touch.
                        live_competitors.extend(
                            row for row in self.pending
                            if row is not pending
                            and row.action.kind.value == 'play_card'
                        )
                        if live_competitors:
                            if not getattr(pending, 'retry_waiting', False):
                                pending.retry_waiting = True
                                self.log('action_retry_waiting',
                                         card=action.card_id,
                                         slot=action.hand_slot,
                                         command_seq=pending.command_seq,
                                         tick=state.tick,
                                         waiting_for=min(
                                             row.command_seq
                                             for row in live_competitors),
                                         reason='live_ack_watch')
                            continue

                        retry_probe_tick = int(
                            getattr(pending, 'retry_probe_tick', -1))
                        if retry_probe_tick < 0:
                            pending.retry_waiting = False
                            pending.retry_probe_tick = int(state.tick)
                            pending.retry_probe_cycle = self._native_cycle(
                                state, action.owner)
                            pending.retry_probe_elixir = (
                                float(state.elixir)
                                if state.elixir is not None else None)
                            self._fresh_state_required = True
                            self.log('action_retry_armed',
                                     card=action.card_id,
                                     slot=action.hand_slot,
                                     command_seq=pending.command_seq,
                                     tick=state.tick,
                                     ack_timeout_ms=round(
                                         ack_timeout_seconds * 1000),
                                     retry_count=pending.retry_count + 1)
                            continue
                        if int(state.tick) <= retry_probe_tick:
                            continue
                        raw_hand_card = self._authoritative_hand_card(
                            state, action.hand_slot, action.owner)
                        current_cycle = self._native_cycle(
                            state, action.owner)
                        same_hand = (
                            raw_hand_card is not None
                            and int(raw_hand_card) == hand_baseline
                        )
                        probe_cycle = getattr(
                            pending, 'retry_probe_cycle', None)
                        same_cycle = (
                            probe_cycle is None
                            or current_cycle == probe_cycle
                        )
                        probe_elixir = getattr(
                            pending, 'retry_probe_elixir', None)
                        no_cost_drop = (
                            probe_elixir is None
                            or state.elixir is None
                            or float(state.elixir) >
                               float(probe_elixir) - pending.cost + 0.15
                        )
                        if same_hand and same_cycle and no_cost_drop:
                            self.ack_watch.remove(pending)
                            pending.state = 'queued'
                            pending.retry_count += 1
                            pending.retry_probe_tick = -1
                            pending.retry_probe_cycle = None
                            pending.retry_probe_elixir = None
                            pending.retry_waiting = False
                            pending.due = now
                            pending.expires = (
                                now + config.ACTION_MAX_LATENESS_SECONDS)
                            pending.input_completed_at = 0.0
                            pending.ack_timeout_seconds = 0.0
                            self.pending.append(pending)
                            self._drop_prediction(pending.command_seq)
                            self.log('action_retry_queued',
                                     card=action.card_id,
                                     slot=action.hand_slot,
                                     command_seq=pending.command_seq,
                                     tick=state.tick,
                                     retry_count=pending.retry_count,
                                     evidence='fresh_stable_hand_cycle_and_elixir')
                            continue
                    self.ack_watch.remove(pending)
                    # A missing ACK is ambiguous: the touch may have reached
                    # the game while telemetry was late.  Keep its virtual
                    # unit briefly so the next policy frame does not spend a
                    # second card on an apparently untouched threat.  This
                    # does not disable the card or block other slots; a later
                    # authoritative entity/hand update removes it normally.
                    prediction_retained = self._retain_uncertain_prediction(
                        pending.command_seq, now)
                    self.cooldowns[action.hand_slot] = (action.card_id, now + 1)
                    # A completed ADB input with no observed hand transition
                    # means this attempt is ambiguous/missed, but it is not
                    # a transport failure.  Do not replay the same write and
                    # do not halt the match; briefly cool the slot and let
                    # the policy continue with fresh state.
                    self.log('action_missed', card=action.card_id, slot=action.hand_slot,
                             command_seq=pending.command_seq, outcome='unknown',
                             continue_running=True,
                             ack_timeout_ms=round(ack_timeout_seconds * 1000),
                             uncertain_prediction_seconds=config.UNCERTAIN_PREDICTION_SECONDS)
                    # A missed touch leaves the live hand unchanged.  Give
                    # the next probe frame time to arrive and suppress only
                    # this exact card/target briefly; other cards remain
                    # available and the card itself is never disabled.
                    # A fresh frame is required below. Do not add a global
                    # global sleep after a missed ACK: it delays every other
                    # playable card even when the touch worker has finished.
                    # Slot, resource, and identical-action guards still apply.
                    self._recent_misses[self._action_key(action)] = now + 1.0
                    self._fresh_state_required = True
                    # On some hosts the touch is accepted before hand/elixir
                    # telemetry rotates. If this attempted play already had a
                    # concrete defensive threat assignment, keep only that
                    # threat locally reserved instead of freezing every policy
                    # decision behind the global settle/preview gate.
                    if self._commit_threat_reservation(
                            pending, state, now, confidence='uncertain'):
                        pass
                    elif config.ENABLE_MODEL_PREDICTION_OVERLAY and prediction_retained:
                        # The transport completed and the model still sees a
                        # short-lived virtual version of the submitted card.
                        # That prediction, together with reserved elixir and
                        # the exact-action miss cooldown, is enough to avoid a
                        # second stale answer without freezing unrelated play.
                        self.log('post_action_settle_skipped',
                                 command_seq=pending.command_seq,
                                 card=action.card_id,
                                 reason='uncertain_prediction_ack_timeout',
                                 protection_ms=round(
                                     config.UNCERTAIN_PREDICTION_SECONDS * 1000))
                    else:
                        self._arm_post_action_recheck(
                            state, pending, reason='ack_timeout')
        for pending in list(self.spawn_watch):
            action = pending.action
            player = next(p for p in state.raw['players'] if p['owner'] == action.owner)
            hero_members = {eid for r in player.get('ability_runtime', [])
                if r.get('known') is True and r.get('ability_name') == ABILITY
                for eid in r.get('members', [])}
            evolved_play = action.card_id in BINDINGS and action.metadata.get('policy_effective_form_code') == 1
            spawned = [e for e in state.entities if e['id'] not in pending.prior_entities and
                e.get('owner') == action.owner and (is_evolved_entity(e, action.card_id) if evolved_play else (e.get('card_id') == action.card_id or
                (action.card_id == MUSKETEER and action.metadata.get('policy_effective_form_code') == 2
                 and e.get('card_id') == 203000014 and e['id'] in hero_members)))]
            if spawned:
                target = action_world(action)
                nearest = min(spawned, key=lambda e: (e['x']-target[0])**2 + (e['y']-target[1])**2)
                hero_carrier = any(r.get('known') is True and r.get('ability_name') == ABILITY
                    and r.get('members') == [nearest['id']] for r in player.get('ability_runtime', []))
                self.log('spawn_observed', card=action.card_id, target_world=target,
                    observed_world=[nearest['x'], nearest['y']], entity_id=nearest['id'],
                    command_seq=pending.command_seq,
                    tick=state.tick, input_to_observation_ms=(now-pending.sent_at)*1000,
                    observation_is_ack_gated=True,
                    selected_form=action.metadata.get('policy_effective_form_code', 0),
                    hero_carrier_confirmed=True if hero_carrier else None,
                    evolution_form_confirmed=True if evolved_play and is_evolved_entity(nearest, action.card_id) else None,
                    deployment_lineage_known=False,
                    note='first observed source-card match after hand ACK; not an exact spawn timestamp')
                self.confirmed_actions += 1
                self.spawn_watch.remove(pending)
            elif now - pending.sent_at > 3:
                self.log('spawn_unobserved', card=action.card_id, slot=action.hand_slot,
                         command_seq=pending.command_seq, outcome='unknown')
                self.spawn_watch.remove(pending)
        if self.future is not None or self.fault:
            return
        for pending in self.pending:
            if pending.state != 'queued':
                continue
            if now < pending.due:
                break
            action = pending.action
            skill = action.kind.value == 'activate_ability'
            validation_started = time.perf_counter()
            if state.local_owner != action.owner or (not skill and state.hand_cards[action.hand_slot] != action.card_id) or not validate(action, state):
                self.pending.remove(pending)
                self.log('action_rejected', reason='live_revalidation', action=action.to_dict())
                break
            now = time.perf_counter()
            if now > pending.expires:
                self.pending.remove(pending)
                self.log('action_expired', card=action.card_id, decision_tick=pending.decision_tick)
                break
            pending.state = 'sent'
            # Count only real Android input attempts. Queued actions rejected
            # by live revalidation or expiry never touched the device and must
            # not consume --max-actions.
            self.attempted_actions += 1
            pending.sent_at = now
            pending.sent_tick = state.tick
            pending.prior_elixir = float(state.elixir)
            pending.prior_cycle = self._native_cycle(
                state, action.owner) if not skill else None
            pending.prior_raw_hand_card = (
                self._raw_hand_card(state, action.hand_slot, action.owner)
                if not skill else None
            )
            # A retry reuses the same logical command so resource accounting
            # remains single-counted. Refresh that reservation timestamp
            # instead of stacking a second virtual spend for the same card.
            self._clear_spend(pending.command_seq)
            self.unconfirmed_spend.append((now, pending.cost, pending.command_seq))
            prediction_lifetime = (config.PREDICTION_LATENCY_COMPENSATION_MS / 1000.0
                                   + config.PREDICTION_HORIZON_TICKS * config.TICK_SECONDS + 0.4)
            self._drop_prediction(pending.command_seq)
            self.predictions.append({'action': action, 'command_seq': pending.command_seq,
                                     'expires_at': now + prediction_lifetime})
            pending.prior_entities = frozenset(e['id'] for e in state.entities)
            if action.card_id in BINDINGS and action.metadata.get('policy_effective_form_code') == 1:
                player = next(p for p in state.raw['players'] if p['owner'] == action.owner)
                pending.prior_evolution_progress = next((r.get('evolution_progress')
                    for r in player.get('card_runtime', []) if r.get('card_id') == action.card_id), None)
            self.active = pending
            if skill:
                self.ability_locks.add(action.source_entity)  # one attempt per finite-charge carrier, even on timeout
            self.future = self.pool.submit(self.actuator.activate_ability if skill else self.actuator.deploy_action, action)
            self.log('input_started', card=action.card_id, slot=action.hand_slot,
                command_seq=pending.command_seq,
                decision_tick=pending.decision_tick, tick=state.tick,
                policy_wait_ms=action.metadata.get('policy_delay_offset_ms'),
                base_schedule_ticks=action.metadata.get('base_latency_ticks'),
                execute_offset_ticks=action.execute_offset_ticks,
                schedule_lateness_ms=(now-pending.due)*1000,
                decision_to_input_ms=(now-pending.decision_at)*1000,
                validation_ms=(now-validation_started)*1000,
                receive_to_input_submit_ms=(now-state.received_at)*1000,
                ability=action.ability_id, source_entity=action.source_entity,
                retry_count=getattr(pending, 'retry_count', 0),
                screen=self.actuator.ability_screen(action) if skill else self.actuator.calibration.action_to_screen(action))
            break

    def close(self):
        self.pending.clear()
        self.ack_watch.clear()
        self.pool.shutdown(wait=True, cancel_futures=True)
        self.actuator.close()
